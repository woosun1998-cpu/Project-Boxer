/**
 * Prepare static assets for Vercel deploy.
 *
 * 1) Force-copy frontend/video/*.mp4 -> public/video/*.mp4
 * 2) Copy public assets into frontend output tree
 * 3) Write frontend/js/config/api-env.js from process.env.API_URL
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const PUBLIC = path.join(ROOT, "public");
const FRONTEND = path.join(ROOT, "frontend");
const FRONTEND_VIDEO = path.join(FRONTEND, "video");
const PUBLIC_VIDEO = path.join(PUBLIC, "video");

const MEDIA_EXT = new Set([".mp4", ".mov", ".webm", ".m4a", ".mkv", ".ogg"]);

const COPY_RULES = [
  { from: PUBLIC_VIDEO, to: FRONTEND_VIDEO, label: "public/video -> frontend/video" },
  {
    from: path.join(PUBLIC, "assets", "videos"),
    to: path.join(FRONTEND, "imboxer", "assets", "videos"),
    label: "public/assets/videos -> frontend/imboxer/assets/videos",
  },
  {
    from: path.join(PUBLIC, "assets", "images"),
    to: path.join(FRONTEND, "imboxer", "assets", "images"),
    label: "public/assets/images -> frontend/imboxer/assets/images",
  },
];

function ensureDir(dir) {
  fs.mkdirSync(dir, { recursive: true });
}

function isMedia(file) {
  return MEDIA_EXT.has(path.extname(file).toLowerCase());
}

function formatBytes(n) {
  if (n < 1024) return `${n} B`;
  if (n < 1024 * 1024) return `${(n / 1024).toFixed(1)} KB`;
  return `${(n / (1024 * 1024)).toFixed(1)} MB`;
}

function listFilesRecursive(dir, onlyMedia) {
  const out = [];
  if (!fs.existsSync(dir)) return out;
  for (const name of fs.readdirSync(dir)) {
    if (name === ".gitkeep" || name === ".gitignore" || name === "README.md") continue;
    const abs = path.join(dir, name);
    const st = fs.statSync(abs);
    if (st.isDirectory()) {
      out.push(...listFilesRecursive(abs, onlyMedia));
    } else if (!onlyMedia || isMedia(abs)) {
      out.push(abs);
    }
  }
  return out;
}

function forceCopyFrontendMp4ToPublic() {
  const report = { copied: 0, failed: 0, bytes: 0, errors: [] };
  ensureDir(PUBLIC_VIDEO);

  if (!fs.existsSync(FRONTEND_VIDEO)) {
    console.log("[sync] frontend/video not found; skip force-copy");
    return report;
  }

  const sources = fs
    .readdirSync(FRONTEND_VIDEO)
    .filter((n) => n.toLowerCase().endsWith(".mp4"))
    .map((n) => path.join(FRONTEND_VIDEO, n));

  console.log(`[sync] force copy mp4: ${sources.length} file(s)`);
  for (const src of sources) {
    const name = path.basename(src);
    const dest = path.join(PUBLIC_VIDEO, name);
    try {
      const st = fs.statSync(src);
      fs.copyFileSync(src, dest);
      report.copied += 1;
      report.bytes += st.size;
      console.log(`  [ok] ${name} (${formatBytes(st.size)})`);
    } catch (e) {
      report.failed += 1;
      report.errors.push(`${name}: ${e.message || e}`);
      console.warn(`  [warn] copy failed: ${name} -> ${e.message || e}`);
    }
  }
  return report;
}

function copyDirMerge(srcRoot, dstRoot) {
  const report = { copied: 0, failed: 0, bytes: 0, errors: [] };
  ensureDir(dstRoot);
  const files = listFilesRecursive(srcRoot, false);

  for (const src of files) {
    const rel = path.relative(srcRoot, src);
    const dst = path.join(dstRoot, rel);
    try {
      ensureDir(path.dirname(dst));
      const st = fs.statSync(src);
      fs.copyFileSync(src, dst);
      report.copied += 1;
      report.bytes += st.size;
    } catch (e) {
      report.failed += 1;
      report.errors.push(`${rel}: ${e.message || e}`);
    }
  }
  return report;
}

function writeApiEnv() {
  const apiUrl = (process.env.API_URL || "")
    .trim()
    .replace(/\/$/, "");
  const out = path.join(FRONTEND, "js", "config", "api-env.js");
  ensureDir(path.dirname(out));
  const content =
    "/** Auto-generated by build */\n" +
    "(function (g) {\n" +
    `  g.__BOXER_API_URL__ = ${JSON.stringify(apiUrl)};\n` +
    "})(typeof window !== \"undefined\" ? window : globalThis);\n";
  fs.writeFileSync(out, content, "utf8");

  console.log(`[api] API_URL set -> ${apiUrl}`);
}

function printPublicVideoSummary() {
  const files = listFilesRecursive(PUBLIC_VIDEO, true).filter((f) => f.toLowerCase().endsWith(".mp4"));
  console.log(`[video] public/video mp4 count: ${files.length}`);
  for (const f of files) {
    const rel = path.relative(ROOT, f).split(path.sep).join("/");
    console.log(`  - ${rel}`);
  }
}

function main() {
  console.log("[prepare-static] start");

  writeApiEnv();

  const syncReport = forceCopyFrontendMp4ToPublic();
  console.log(
    `[sync] copied=${syncReport.copied}, failed=${syncReport.failed}, bytes=${formatBytes(syncReport.bytes)}`,
  );
  if (syncReport.errors.length) {
    console.warn("[sync] errors (build continues):");
    syncReport.errors.forEach((e) => console.warn(`  - ${e}`));
  }

  for (const rule of COPY_RULES) {
    const r = copyDirMerge(rule.from, rule.to);
    console.log(`[copy] ${rule.label}: copied=${r.copied}, failed=${r.failed}, bytes=${formatBytes(r.bytes)}`);
    if (r.errors.length) {
      console.warn("  errors:");
      r.errors.slice(0, 10).forEach((e) => console.warn(`   - ${e}`));
      if (r.errors.length > 10) console.warn(`   ...and ${r.errors.length - 10} more`);
    }
  }

  printPublicVideoSummary();

  console.log("[prepare-static] done (build continues even on copy warnings)");
}

main();
